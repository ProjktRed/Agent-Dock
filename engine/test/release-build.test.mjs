import test from 'node:test';
import assert from 'node:assert/strict';
import childProcess from 'node:child_process';
import {syncBuiltinESMExports} from 'node:module';
import {mkdtempSync,mkdirSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {buildStaging} from '../../scripts/release-local.mjs';

test('local release returns the metadata regenerated by its build, not stale staging metadata',t=>{
  const root=mkdtempSync(path.join(tmpdir(),'release-build-'));
  const repo=path.join(root,'repo');mkdirSync(repo);
  const fresh={commit:'123456789',shortCommit:'1234567',subject:'fresh',branch:'dev',source:'source',builtAt:'new'};
  writeFileSync(path.join(repo,'build-info.json'),JSON.stringify({shortCommit:'stale'}));
  const calls=[];
  t.mock.method(childProcess,'spawnSync',(command,args,opts)=>{
    calls.push([command,args,opts]);
    if(args[0]==='electron-vite')writeFileSync(path.join(repo,'build-info.json'),JSON.stringify(fresh));
    if(args[0]==='electron-builder'){
      mkdirSync(path.join(root,'dist','win-unpacked'),{recursive:true});
      writeFileSync(path.join(root,'dist','win-unpacked','AgentDock.exe'),'fixture');
    }
    return {status:0,stdout:'',stderr:''};
  });
  syncBuiltinESMExports();
  try {
    const result=buildStaging({repo,source:'source',branch:'dev',staging:root});
    assert.deepEqual(result,{unpacked:path.join(root,'dist','win-unpacked'),info:fresh});
    assert.equal(calls.length,3);
    assert.equal(calls[1][2].env.AGENT_DOCK_BUILD_SOURCE,'source');
    assert.equal(calls[1][2].env.AGENT_DOCK_BUILD_BRANCH,'dev');
  } finally {t.mock.restoreAll();syncBuiltinESMExports();rmSync(root,{recursive:true,force:true});}
});
